import { describe, expect, it } from "vitest";
import { isPublicAddress } from "./index";

// S-05：DNS 解析後拒絕私有、迴路、鏈路本地與保留位址
describe("isPublicAddress", () => {
  it.each([
    "127.0.0.1",
    "127.255.255.254",
    "10.0.0.1",
    "10.255.255.255",
    "172.16.0.1",
    "172.31.255.255",
    "192.168.1.1",
    "169.254.169.254",
    "0.0.0.0",
    "100.64.0.1",
    "192.0.0.8",
    "192.0.2.1",
    "198.18.0.1",
    "198.51.100.7",
    "203.0.113.9",
    "224.0.0.1",
    "240.0.0.1",
    "255.255.255.255",
  ])("拒絕 IPv4 %s", (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each([
    "::",
    "::1",
    "0:0:0:0:0:0:0:1",
    "fe80::1",
    "fc00::1",
    "fd12:3456::1",
    "ff02::1",
    "2001:db8::1",
    // IPv4 對應位址與轉換前綴內嵌私有位址
    "::ffff:127.0.0.1",
    "::ffff:7f00:1",
    "::ffff:169.254.169.254",
    "64:ff9b::10.0.0.1",
    "2002:0a00:0001::1",
    // Teredo
    "2001::1",
    "100::1",
  ])("拒絕 IPv6 %s", (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each(["8.8.8.8", "1.1.1.1", "172.32.0.1", "100.128.0.1", "2001:4860:4860::8888", "2606:4700::1111", "::ffff:8.8.8.8"])(
    "允許公開位址 %s",
    (ip) => {
      expect(isPublicAddress(ip)).toBe(true);
    },
  );

  it.each(["", "localhost", "1.2.3", "256.0.0.1", "01.2.3.4", "1::2::3", "fe80::1%eth0", "::ffff:999.0.0.1"])("無法解析的位址一律拒絕：%s", (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });
});
